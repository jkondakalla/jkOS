// gen.mjs — project the widget manifest into the files that must agree with it.
//
//   node packages/widgets/scripts/gen.mjs           write them   (pnpm widgets:gen)
//   node packages/widgets/scripts/gen.mjs --check   exit 1 if any is stale (pnpm check:widgets)
//
// Outputs:
//   apps/ordeck/src/hud/nodes.gen.ts — the `WidgetNode` union ORDECK renders against,
//     plus `Tone` and `IconName`. Because the renderer's primitive map
//     is `{ [K in WidgetNode['t']]: … }`, tsc refuses one that misses a manifest kind
//     or keeps a dead one — the manifest and the renderers cannot drift.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NODES, TONES, ICON_NAMES } from '../src/manifest.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const CHECK = process.argv.includes('--check');

const lit = (v) => `'${String(v).replace(/'/g, "\\'")}'`;
const union = (vs) => vs.map(lit).join(' | ');
const docLine = (text, indent) => `${indent}/** ${text.replace(/\*\//g, '*\\/')} */\n`;

function tsType(p) {
  switch (p.type) {
    case 'binding': return 'Binding';
    case 'tone': return 'ToneBinding';
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'string':
    case 'field': return 'string';
    case 'enum': return union(p.values);
    case 'cmd': return 'CommandRef';
    case 'node': return 'WidgetNode';
    case 'nodes': return 'WidgetNode[]';
    default: throw new Error(`gen: unknown prop type ${p.type}`);
  }
}

function nodesTs() {
  let out = '';
  out += '// GENERATED by packages/widgets/scripts/gen.mjs from packages/widgets/src/manifest.js — do not edit.\n';
  out += '// Regenerate with `pnpm widgets:gen`; `pnpm check:widgets` fails when this file is stale.\n\n';
  out += "import type { Binding, ToneBinding, CommandRef } from './types';\n\n";
  out += '/** The status palette a tone names — semantic constants, never accent-derived. */\n';
  out += `export type Tone = ${union(TONES)};\n\n`;
  out += '/** The curated line-icon set. */\n';
  out += `export type IconName = ${union(ICON_NAMES)};\n\n`;
  out += '/** The composable display vocabulary — one variant per manifest kind. */\n';
  out += 'export type WidgetNode =\n';
  for (const [t, spec] of Object.entries(NODES)) {
    const reads = [].concat(spec.reads ?? []);
    out += docLine(`${spec.label} — ${spec.hint}.${reads.length ? ` Reads ${reads.map((r) => `\`${r}\``).join(' and ')}.` : ''}`, '  ');
    const fields = [`t: ${lit(t)}`];
    for (const [name, p] of Object.entries(spec.props)) {
      const f = `${name}${p.required ? '' : '?'}: ${tsType(p)}`;
      fields.push(p.doc ? `/** ${p.doc} */ ${f}` : f);
    }
    out += `  | { ${fields.join('; ')} }\n`;
  }
  out = out.replace(/\n$/, ';\n');
  return out;
}

const OUTPUTS = [
  { path: 'apps/ordeck/src/hud/nodes.gen.ts', build: nodesTs },
];

let stale = 0;
for (const { path, build } of OUTPUTS) {
  const abs = resolve(ROOT, path);
  const next = build();
  const now = existsSync(abs) ? readFileSync(abs, 'utf8') : null;
  if (now === next) { if (CHECK) console.log(`✓ ${path} is fresh`); continue; }
  if (CHECK) { console.error(`✗ ${path} is stale — run \`pnpm widgets:gen\``); stale++; continue; }
  writeFileSync(abs, next);
  console.log(`wrote ${path}`);
}
if (stale) process.exit(1);
