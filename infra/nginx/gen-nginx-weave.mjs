#!/usr/bin/env node
// gen-nginx-weave.mjs — generate the Weave peer-proxy nginx includes from ONE table.
//
// The shared same-origin peer-proxy include is the edge half of Weave's transport.
// Keeping it generated means "add a peer" is one row here, not hand-edited nginx —
// the registry-driven onboarding the standard promises, at the edge. This emits BOTH
// environments from the same PEERS table so prod and staging can't drift:
//
//   * weave-proxy.conf          PROD: included by every prod app server block. The
//                               peer locations are NOT auth_request-gated (each
//                               backend enforces its own JWT) and hit the bare
//                               <container>:<port> upstreams.
//   * weave-proxy-staging.conf  STAGING: included by the single staging server block.
//                               The SAME locations, but admin-gated (auth_request +
//                               the @staging_* error pages) and pointed at the
//                               staging-<container> upstreams. Staging is one origin,
//                               so the whole surface sits behind the admin gate.
//
//   node infra/nginx/gen-nginx-weave.mjs           # (re)write BOTH files
//   node infra/nginx/gen-nginx-weave.mjs --check    # exit 1 if EITHER is out of sync (CI)
//
// NOTE: the internal upstream (container:port) is INFRA config, not in the app
// registry (which stores only edge-relative api_base/health_path). So this table is
// the source for the addresses; it must stay consistent with the registry's
// api_base/health_path — `--check` is the guard. The staging file references the
// named locations (/_auth_admin_check, @staging_unauthorized, @staging_forbidden,
// @staging_unavailable) defined inline in standalone.conf's staging server block.
// After regenerating, RESTART nginx (the confs are bind-mounts; reload won't re-read
// a replaced inode) — and ensure weave-proxy-staging.conf is mounted (compose +
// validate_nginx in infra/scripts/lib-deploy.sh both mount it).

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
// Single source: the same APPS table the jkAuth registry seed + Weave manifest derive
// from (ToDo A2). Relative path, not the bare specifier — this script is run from the
// repo root (`node infra/nginx/...`), where @jkos/* is not resolvable. CJS via interop.
import { peers, edgeApps } from '../../packages/suite-manifest/apps.js'

const DIR = dirname(fileURLToPath(import.meta.url))
const OUT = join(DIR, 'weave-proxy.conf')
const OUT_STAGING = join(DIR, 'weave-proxy-staging.conf')
const OUT_APPS = join(DIR, 'apps-generated.conf')
const OUT_APPS_STAGING = join(DIR, 'apps-generated-staging.conf')

// Peers reachable same-origin from every suite origin, DERIVED from @jkos/suite-manifest:
// `health`/`apiPrefix` are computed from each app's id (so they mirror the registry
// health_path/api_base by construction); `upstream` is the docker address (the one
// infra fact the source stores). Staging derives its upstream by prefixing `staging-`
// (set once, in stagingUpstream). LazurOS (`kind:'lazuros'`) is the host-network special
// case rendered by lazurosBlock; its health/apiPrefix are skipped in the loops below.
const PEERS = peers()

// Staging container names are the prod name with a `staging-` prefix (the convention
// enforced in standalone.conf's "Adding a new STAGING service" note).
const stagingUpstream = (upstream) => `staging-${upstream}`

// The admin gate every staging location carries (staging is a single admin-only
// origin). LazurOS has no @staging_unavailable (it's the host gateway, not a
// compose service), so its gate omits the 502/503/504 line.
const GATE = [
  'auth_request /_auth_admin_check;',
  'error_page 401 = @staging_unauthorized;',
  'error_page 403 = @staging_forbidden;',
]
const GATE_UNAVAIL = [...GATE, 'error_page 502 503 504 = @staging_unavailable;']
// 4-space body indent, matching the location bodies below; '' in prod (no gate).
const gateBlock = (lines, staging) => (staging ? lines.map(l => `    ${l}`).join('\n') + '\n' : '')

const HEADER = `# weave-proxy.conf — the shared same-origin peer-proxy include (PROD).
#
# GENERATED by infra/nginx/gen-nginx-weave.mjs — do not hand-edit; run the script.
#
# The edge half of Weave's "same-origin everywhere" transport: the /api/<peer>/* and
# /health/<peer> locations that let a browser on ANY suite origin reach ANY peer's
# API same-origin, so the jkos_token cookie flows with no CORS surface. \`include\`d
# into EVERY prod app server block in standalone.conf (the portal, BeigeBoard,
# jkAuth, SylibOS). Each location is self-contained (it \`set $hud\` itself), so it
# transplants into any server block; each backend still enforces its own JWT — these
# are deliberately NOT auth_request-gated. Staging gets its own admin-gated twin
# (weave-proxy-staging.conf), generated from the SAME table.
#
#   node infra/nginx/gen-nginx-weave.mjs           # write both files
#   node infra/nginx/gen-nginx-weave.mjs --check    # CI: assert they're in sync
# Adding a peer = one row in the script, then RESTART nginx (NOT reload — bind-mount).`

const HEADER_STAGING = `# weave-proxy-staging.conf — the same-origin peer-proxy include (STAGING).
#
# GENERATED by infra/nginx/gen-nginx-weave.mjs — do not hand-edit; run the script.
#
# The staging twin of weave-proxy.conf, from the SAME PEERS table, so the two can't
# drift. Staging is a single admin-only origin (staging.jkos.net), so every peer
# location here is admin-gated: each carries \`auth_request /_auth_admin_check\` plus
# the @staging_unauthorized / @staging_forbidden / @staging_unavailable error pages,
# and points at the staging-<container> upstreams. \`include\`d ONCE — into the staging
# server block in standalone.conf, which defines those named locations + the
# /_auth_admin_check subrequest.
#
#   node infra/nginx/gen-nginx-weave.mjs           # write both files
#   node infra/nginx/gen-nginx-weave.mjs --check    # CI: assert they're in sync
# Adding a peer = one row in the script, then RESTART nginx (NOT reload — bind-mount).`

function lazurosBlock(staging) {
  return `# LazurOS AI gateway — host network (WoL broadcast), reached via the host gateway.
# Prefix PRESERVED (no trailing slash on proxy_pass): unlike the other peers, the State
# node registers its routes at their full edge paths — /api/lazuros/health, and the
# capability paths declared in backend/docs.js — so the path a capability doc ADVERTISES
# is the path the server actually serves. Stripping here would 404 every one of them.
# Buffering off + long read timeout for streamed NDJSON tokens.
location /api/lazuros/ {
${gateBlock(GATE, staging)}    proxy_pass         http://host.docker.internal:8080;
    proxy_http_version 1.1;
    proxy_buffering    off;
    proxy_read_timeout 600s;
    proxy_set_header   Host              $host;
    proxy_set_header   X-Real-IP         $remote_addr;
    proxy_set_header   X-Forwarded-For   $proxy_add_x_forwarded_for;
    proxy_set_header   X-Forwarded-Proto $scheme;
}`
}

// The LazurOS test console — STAGING ONLY, and deliberately so: it is the surface for
// exercising the gateway (submit a capability, watch the job walk its states) before any
// app depends on it. Pretty path -> the console the State node serves under its own API
// prefix. Prod gets no /LazurOS: nothing in prod should be driving the gateway by hand.
function lazurosConsoleBlock() {
  return `# LazurOS test console (staging only) — https://staging.jkos.net/LazurOS
location = /LazurOS { return 302 /LazurOS/; }
location /LazurOS/ {
${gateBlock(GATE, true)}    proxy_pass         http://host.docker.internal:8080/api/lazuros/console/;
    proxy_http_version 1.1;
    proxy_set_header   Host              $host;
    proxy_set_header   X-Real-IP         $remote_addr;
    proxy_set_header   X-Forwarded-For   $proxy_add_x_forwarded_for;
    proxy_set_header   X-Forwarded-Proto $scheme;
}`
}

function healthBlock(p, staging) {
  const upstream = staging ? stagingUpstream(p.upstream) : p.upstream
  return `location = ${p.health} {
${gateBlock(GATE_UNAVAIL, staging)}    set $hud http://${upstream};
    rewrite ^.*$ /health break;
    proxy_pass       $hud;
    proxy_set_header Host $host;
}`
}

function apiBlock(p, staging) {
  const upstream = staging ? stagingUpstream(p.upstream) : p.upstream
  const re = p.apiPrefix.replace(/\//g, '\\/').replace(/\\\/$/, '\\/(.*)$')
  return `location ${p.apiPrefix} {
${gateBlock(GATE_UNAVAIL, staging)}    set $hud http://${upstream};
    rewrite ^${re} /api/$1 break;
    proxy_pass       $hud;
    proxy_set_header Host              $host;
    proxy_set_header X-Real-IP         $remote_addr;
    proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
}`
}

function build(staging) {
  const blocks = []
  // health probes first (one per peer that has one), then api prefixes — matches
  // the original portal ordering; lazuros leads (special-cased).
  for (const p of PEERS) if (p.kind === 'lazuros') {
    blocks.push(lazurosBlock(staging))
    if (staging) blocks.push(lazurosConsoleBlock())
  }
  for (const p of PEERS) if (p.health && p.kind !== 'lazuros') blocks.push(healthBlock(p, staging))
  for (const p of PEERS) if (p.apiPrefix && p.kind !== 'lazuros') blocks.push(apiBlock(p, staging))
  const header = staging ? HEADER_STAGING : HEADER
  return `${header}\n# >>> GENERATED REGION <<<\n\n${blocks.join('\n')}\n# >>> END GENERATED REGION <<<\n`
}

/* ── Per-app edge server blocks (ToDo C2) ────────────────────────────────────
 * The OTHER hand-written nginx step a new app needed: a prod origin server block (and a
 * staging admin-gated subpath). Generated for apps that opt in with edge:'standard' in
 * @jkos/suite-manifest — an SPA served at root, proxied to one upstream. The hand-tuned
 * origins (ORDECK portal, jkAuth, BeigeBoard, SylibOS, the staging shell) set no edge and
 * keep their bespoke blocks in standalone.conf, so this never rewrites them. Both files
 * are empty (header only) until the first edge:'standard' app — included unconditionally
 * by standalone.conf (apps-generated.conf at http{} level, apps-generated-staging.conf
 * inside the staging server block, where /_auth_admin_check + @staging_* are defined). */
const EDGE_APPS = edgeApps()

/* ── Digital Asset Links ───────────────────────────────────────────────────────
   The file an Android TWA's link verification fetches from
   https://<origin>/.well-known/assetlinks.json to decide whether the installed
   app may own that origin's links — i.e. whether it opens WITHOUT a URL bar.

   ⚠️ IT CANNOT BE SHIPPED IN THE APP'S public/ DIRECTORY. serveSpa mounts
   express.static, whose `dotfiles` default is 'ignore', so `.well-known/` never
   matches; the `app.get('*')` SPA fallback then answers with index.html at 200.
   The verifier gets HTML, fails, and says nothing useful — the only symptom is a
   URL bar that will not go away. Measured against the real server before this
   existed: `200 text/html`. So it is answered at the EDGE, above the proxy pass.

   Emitted into every generated prod app block AND into jkAuth's hand-tuned block
   in standalone.conf — jkAuth because sign-in is a full-page redirect to a
   DIFFERENT ORIGIN, and an unverified hop drops a toolbar over the login screen
   exactly when the user is typing a password. One source, two emission sites,
   and `--check` asserts standalone.conf still carries this byte-for-byte. */
const ASSETLINKS = JSON.parse(readFileSync(join(DIR, 'assetlinks.json'), 'utf8'))

// Minified onto ONE line: nginx's `return` takes a single quoted string, and a
// multi-line literal would need continuations that the JSON escaping fights.
// JSON never contains a single quote, so the quoting is unambiguous.
const ASSETLINKS_BODY = JSON.stringify(ASSETLINKS.targets)

const ASSETLINKS_LOCATION = `# Digital Asset Links — GENERATED from infra/nginx/assetlinks.json; do not hand-edit.
# Answered at the edge because serveSpa's express.static ignores dotfile paths and
# the SPA fallback would return index.html at 200 (see gen-nginx-weave.mjs).
location = /.well-known/assetlinks.json {
    default_type application/json;
    add_header Cache-Control "public, max-age=300" always;
    return 200 '${ASSETLINKS_BODY}';
}`

const SEC_HEADERS = [
  'add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;',
  'add_header X-Content-Type-Options nosniff always;',
  'add_header X-Frame-Options SAMEORIGIN always;',
  'add_header X-XSS-Protection "1; mode=block" always;',
  'add_header Referrer-Policy "strict-origin-when-cross-origin" always;',
]

const PROXY_HEADERS = [
  'proxy_set_header   Upgrade           $http_upgrade;',
  'proxy_set_header   Connection        "upgrade";',
  'proxy_set_header   Host              $host;',
  'proxy_set_header   X-Real-IP         $remote_addr;',
  'proxy_set_header   X-Forwarded-For   $proxy_add_x_forwarded_for;',
  'proxy_set_header   X-Forwarded-Proto $scheme;',
]

function appServerBlock(a) {
  return `# ${a.name} — GENERATED from @jkos/suite-manifest APPS (edge:'standard'); do not hand-edit.
server {
    listen 80;
    server_name ${a.host};
    return 301 https://$host$request_uri;
}
server {
    listen 443 ssl http2;
    server_name ${a.host};

    ssl_certificate     /etc/nginx/ssl/cert.pem;
    ssl_certificate_key /etc/nginx/ssl/key.pem;
    ssl_protocols       TLSv1.2 TLSv1.3;
    ssl_ciphers         HIGH:!aNULL:!MD5;
    ssl_session_cache   shared:SSL:10m;

${SEC_HEADERS.map(h => '    ' + h).join('\n')}

    client_max_body_size 10m;

    # Weave same-origin peer proxy (every prod origin reaches every peer).
    include /etc/nginx/weave-proxy.conf;

${ASSETLINKS_LOCATION.split('\n').map(l => l ? '    ' + l : l).join('\n')}

    location / {
        set $upstream      http://${a.upstream};
        proxy_pass         $upstream;
        proxy_http_version 1.1;
${PROXY_HEADERS.map(h => '        ' + h).join('\n')}
        proxy_cache_bypass $http_upgrade;
        proxy_read_timeout 60s;
    }
}`
}

function appStagingLocation(a) {
  return `# ${a.name} — GENERATED admin-gated app subpath on staging.jkos.net; do not hand-edit.
# Bare /<id> (no trailing slash) matches neither \`location /<id>/\` below nor any other
# prefix, so it falls through to this server's \`location /\` — the ORDECK portal — and
# the app silently "redirects to ORDECK". Send it to the real subpath first.
location = /${a.id} {
    return 301 https://$host/${a.id}/;
}
location /${a.id}/ {
${GATE_UNAVAIL.map(l => '    ' + l).join('\n')}
    set $upstream http://${stagingUpstream(a.upstream)};
    rewrite ^/${a.id}/(.*) /$1 break;
    proxy_pass         $upstream;
    proxy_http_version 1.1;
${PROXY_HEADERS.map(h => '    ' + h).join('\n')}
    proxy_cache_bypass $http_upgrade;
    proxy_read_timeout 60s;
}`
}

const HEADER_APPS = `# apps-generated.conf — GENERATED standard prod origin server blocks.
#
# GENERATED by infra/nginx/gen-nginx-weave.mjs from @jkos/suite-manifest APPS — do not
# hand-edit; run the script. One <listen 80 redirect> + <listen 443 SPA-at-root> server
# block per app that opts in with edge:'standard' (the scaffolder sets it). \`include\`d at
# the http{} level in standalone.conf. The hand-tuned origins (portal, jkAuth, BeigeBoard,
# SylibOS, staging) set no edge and keep their bespoke blocks. Empty until the first one.
#   node infra/nginx/gen-nginx-weave.mjs           # write
#   node infra/nginx/gen-nginx-weave.mjs --check    # CI: assert in sync
# Adding an app = \`pnpm new-app <id>\`, then RESTART nginx (NOT reload — bind-mount).`

const HEADER_APPS_STAGING = `# apps-generated-staging.conf — GENERATED admin-gated app subpaths (STAGING).
#
# GENERATED by infra/nginx/gen-nginx-weave.mjs from @jkos/suite-manifest APPS — do not
# hand-edit. One \`location /<id>/\` per edge:'standard' app, admin-gated + path-rewritten,
# pointed at the staging-<container> upstream. \`include\`d INSIDE the staging server block
# in standalone.conf (which defines /_auth_admin_check + the @staging_* named locations).
# Empty until the first edge:'standard' app exists.
#   node infra/nginx/gen-nginx-weave.mjs           # write
#   node infra/nginx/gen-nginx-weave.mjs --check    # CI: assert in sync`

function buildApps(staging) {
  const blocks = EDGE_APPS.map(staging ? appStagingLocation : appServerBlock)
  const header = staging ? HEADER_APPS_STAGING : HEADER_APPS
  const region = blocks.length ? `\n${blocks.join('\n\n')}\n` : '\n'
  return `${header}\n# >>> GENERATED REGION <<<\n${region}# >>> END GENERATED REGION <<<\n`
}

const targets = [
  { path: OUT,              content: build(false),     label: 'weave-proxy.conf' },
  { path: OUT_STAGING,      content: build(true),      label: 'weave-proxy-staging.conf' },
  { path: OUT_APPS,         content: buildApps(false), label: 'apps-generated.conf' },
  { path: OUT_APPS_STAGING, content: buildApps(true),  label: 'apps-generated-staging.conf' },
]

/* jkAuth's server block is HAND-TUNED in standalone.conf, so the asset-links
   location has two emission sites. Two sites is a drift trap, and the house rule
   for that is one source plus a conformance test — this is the test. It compares
   the payload, not the whitespace: standalone.conf indents its server blocks four
   further than the generated files, so a byte compare would fail on formatting
   alone and teach everyone to ignore it. */
function checkStandaloneAssetlinks() {
  const conf = join(DIR, 'standalone.conf')
  let text = ''
  try { text = readFileSync(conf, 'utf8') } catch {
    console.error('✗ standalone.conf is unreadable')
    return false
  }
  const found = [...text.matchAll(/location = \/\.well-known\/assetlinks\.json \{[^}]*?return 200 '([^']*)';/gs)]
  if (!found.length) {
    console.error(
      '✗ standalone.conf has no /.well-known/assetlinks.json location. jkAuth is a ' +
      'separate ORIGIN in the sign-in redirect; without it a TWA shows a URL bar over ' +
      'the login screen. Copy the block from apps-generated.conf into the auth.jkos.net server.')
    return false
  }
  const wrong = found.filter(([, body]) => body !== ASSETLINKS_BODY)
  if (wrong.length) {
    console.error(
      `✗ standalone.conf serves asset links that differ from infra/nginx/assetlinks.json\n` +
      `    expected: ${ASSETLINKS_BODY}\n` +
      `    found:    ${wrong.map(([, b]) => b).join('\n              ')}`)
    return false
  }
  console.log(`✓ standalone.conf asset links match assetlinks.json (${found.length} origin(s))`)
  return true
}

if (process.argv.includes('--check')) {
  let drift = !checkStandaloneAssetlinks()
  for (const t of targets) {
    let current = ''
    try { current = readFileSync(t.path, 'utf8') } catch { /* missing → drift */ }
    if (current !== t.content) {
      console.error(`✗ ${t.label} is out of sync with gen-nginx-weave.mjs. Run: node infra/nginx/gen-nginx-weave.mjs`)
      drift = true
    } else {
      console.log(`✓ ${t.label} in sync`)
    }
  }
  process.exit(drift ? 1 : 0)
} else {
  for (const t of targets) {
    writeFileSync(t.path, t.content)
    console.log(`✓ wrote ${t.path}`)
  }
  // standalone.conf is HAND-TUNED and is not regenerated — but the asset-links
  // payload inside it is generated data, and requiring a hand edit every time a
  // signing fingerprint changes is exactly the friction that lets a stale payload
  // ship. So this one delimited block is rewritten in place; everything around it
  // is left alone, and --check still guards the result.
  const conf = join(DIR, 'standalone.conf')
  const before = readFileSync(conf, 'utf8')
  const after = before.replace(
    /(location = \/\.well-known\/assetlinks\.json \{[^}]*?return 200 ')([^']*)(';)/gs,
    (_m, head, _body, tail) => head + ASSETLINKS_BODY + tail)
  if (after !== before) {
    writeFileSync(conf, after)
    console.log(`✓ synced asset links into ${conf}`)
  }
}
